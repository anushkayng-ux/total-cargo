$step = isset($_GET['step']) ? max(1, min(5, (int) $_GET['step'])) : 1;

if ($step === 4 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    // Final install run
    $cfg = $_SESSION['cfg'] ?? [];
    if (empty($cfg)) { flash('error', 'Session expired — start over.'); header('Location: ' . url(1)); exit; }

    // 1. Connect to DB (and create if asked)
    try {
        $pdo = pdo_connect($cfg['db_host'], $cfg['db_port'], $cfg['db_user'], $cfg['db_pass']);
        $exists = $pdo->query("SHOW DATABASES LIKE " . $pdo->quote($cfg['db_name']))->fetchColumn();
        if (!$exists) {
            $pdo->exec("CREATE DATABASE `{$cfg['db_name']}` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        }
        $pdo->exec("USE `{$cfg['db_name']}`");
    } catch (\Throwable $e) {
        flash('error', 'DB connect failed: ' . $e->getMessage());
        header('Location: ' . url(2)); exit;
    }

    // 2. Write .env
    if (!write_env($ENV_PATH, $cfg, $ENV_SAMPLE)) {
        flash('error', 'Could not write .env to ' . $ENV_PATH . '. Check folder permissions.');
        header('Location: ' . url(3)); exit;
    }

    // 2b. Optionally drop a project-root .htaccess so the bare domain serves
    //     /public/ — no /public/ prefix in the URL the user sees.
    if (!empty($cfg['install_htaccess'])) {
        $htOk = write_root_htaccess($ROOT . '/.htaccess');
        flash($htOk ? 'success' : 'warning',
            $htOk ? 'Project-root .htaccess installed — clean URLs enabled (no /public/ prefix).'
                  : 'Could not write .htaccess at project root. Drop the bundled .htaccess there manually.');
    }

    // 3. Either restore SQL dump OR run migrations + seeders
    $log = [];
    if (!empty($cfg['use_dump']) && is_file($DB_DUMP)) {
        $log[] = ['Restoring database.sql', null];
        $r = import_sql_dump($pdo, $DB_DUMP);
        if (!$r['ok']) { flash('error', 'Restore failed: ' . $r['msg']); header('Location: ' . url(3)); exit; }
        $log[count($log) - 1][1] = "OK ({$r['count']} statements)";
    } else {
        $log[] = ['Running migrations', null];
        $r = run_migrations($ROOT);
        if (!$r['ok']) { flash('error', 'Migrate failed: ' . $r['msg']); header('Location: ' . url(3)); exit; }
        $log[count($log) - 1][1] = $r['msg'];

        $log[] = ['Running seeders', null];
        $r = run_seeders($ROOT, ['PermissionSeeder', 'TripExpenseCategorySeeder', 'EmailTemplateSeeder']);
        if (!$r['ok']) { flash('error', 'Seed failed: ' . $r['msg']); header('Location: ' . url(3)); exit; }
        $log[count($log) - 1][1] = 'Applied: ' . implode(', ', $r['applied']);
    }

    // 4. Create super admin
    $log[] = ['Creating super-admin user', null];
    $r = ensure_super_admin($pdo, $cfg['admin_email'], $cfg['admin_pass'], $cfg['admin_name']);
    if (!$r['ok']) { flash('error', 'Admin create failed: ' . $r['msg']); header('Location: ' . url(3)); exit; }
    $log[count($log) - 1][1] = 'User #' . $r['user_id'] . ' (super-admin)';

    // 5. Lock file
    @file_put_contents($LOCK_PATH, date('c') . ' installed by ' . ($_SERVER['REMOTE_ADDR'] ?? 'unknown'));
    $log[] = ['Wrote lock file', $LOCK_PATH];

    $_SESSION['install_log'] = $log;
    $_SESSION['install_done'] = true;
    header('Location: ' . url(5));
    exit;
}

