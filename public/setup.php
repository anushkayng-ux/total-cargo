function h(string $s): string { return htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }
function url(int $step, array $extra = []): string {
    $extra['step'] = $step;
    return basename(__FILE__) . '?' . http_build_query($extra);
}
function flash(string $kind, string $msg): void { $_SESSION['_flash'][] = [$kind, $msg]; }
function pop_flash(): array { $f = $_SESSION['_flash'] ?? []; $_SESSION['_flash'] = []; return $f; }

function pdo_connect(string $host, string $port, string $user, string $pass, ?string $db = null): \PDO
{
    $dsn = "mysql:host={$host};port={$port}" . ($db ? ";dbname={$db}" : '') . ';charset=utf8mb4';
    return new \PDO($dsn, $user, $pass, [
        \PDO::ATTR_ERRMODE => \PDO::ERRMODE_EXCEPTION,
        \PDO::ATTR_PERSISTENT => false,
    ]);
}

function write_root_htaccess(string $path): bool
{
    $content = <<<'HT'
# Generated by public/setup.php
# Rewrites every request to /public/ so the bare domain serves CodeIgniter
# without "/public/" in the URL. Delete this file if your web-server
# DocumentRoot already points at /public/.
DirectoryIndex public/index.php

<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteCond %{REQUEST_URI} !^/public/
    RewriteRule ^(.*)$ public/$1 [L]
</IfModule>

# Block direct HTTP access to sensitive project files.
<FilesMatch "^(\.env|\.env\..*|composer\.json|composer\.lock|spark|preload\.php|phpunit\.xml\.dist|database\.sql|README\.md|INSTALL\.md|USER-GUIDE\.md|FEATURES\.md|LICENSE)$">
    Require all denied
</FilesMatch>
RedirectMatch 404 ^/(app|tests|tools|writable|vendor|builds)(/.*)?$
HT;
    return @file_put_contents($path, $content) !== false;
}

function write_env(string $envPath, array $cfg, string $sampleEnv): bool
{
    // Prefer copying from `env` (the CI4 sample) and overwriting our keys
    $template = is_file($sampleEnv) ? file_get_contents($sampleEnv) : '';
    if (!is_string($template) || $template === '') {
        // Build a minimal template
        $template = "CI_ENVIRONMENT = production\n\n"
            . "app.baseURL = ''\n"
            . "database.default.hostname = 127.0.0.1\n"
            . "database.default.database = \n"
            . "database.default.username = \n"
            . "database.default.password = \n"
            . "database.default.DBDriver = MySQLi\n"
            . "database.default.port = 3306\n\n"
            . "encryption.key = \n";
    }

    $set = function (string $contents, string $key, string $value) {
        $line  = $key . ' = ' . (preg_match('/\s/', $value) || $value === '' ? "'" . str_replace("'", "\\'", $value) . "'" : $value);
        // Match: optional `# `, key, optional spaces, =, anything until EOL
        $pattern = '/^[#\s]*' . preg_quote($key, '/') . '\s*=\s*.*$/m';
        if (preg_match($pattern, $contents)) {
            return preg_replace($pattern, $line, $contents, 1);
        }
        return rtrim($contents) . "\n" . $line . "\n";
    };

    $template = $set($template, 'CI_ENVIRONMENT',           $cfg['env']);
    $template = $set($template, 'app.baseURL',              $cfg['baseUrl']);
    $template = $set($template, 'app.indexPage',            '');
    $template = $set($template, 'app.forceGlobalSecureRequests', $cfg['https'] ? 'true' : 'false');
    $template = $set($template, 'database.default.hostname',$cfg['db_host']);
    $template = $set($template, 'database.default.port',    $cfg['db_port']);
    $template = $set($template, 'database.default.database',$cfg['db_name']);
    $template = $set($template, 'database.default.username',$cfg['db_user']);
    $template = $set($template, 'database.default.password',$cfg['db_pass']);
    $template = $set($template, 'database.default.DBDriver','MySQLi');
    $template = $set($template, 'encryption.key',           $cfg['enc_key']);
    $template = $set($template, 'tpt.appName',              $cfg['app_name']);
    $template = $set($template, 'tpt.companyName',          $cfg['company_name']);

    return file_put_contents($envPath, $template) !== false;
}

function preflight(): array
{
    global $ROOT;
    $checks = [];
    $checks[] = ['PHP version ≥ 8.2', PHP_VERSION_ID >= 80200, PHP_VERSION];
    foreach (['mysqli','pdo_mysql','mbstring','intl','curl','openssl','json','fileinfo'] as $ext) {
        $checks[] = ["Extension: $ext", extension_loaded($ext), extension_loaded($ext) ? 'loaded' : 'MISSING'];
    }
    foreach ([
        'writable/'             => $ROOT . '/writable',
        'writable/cache/'       => $ROOT . '/writable/cache',
        'writable/session/'     => $ROOT . '/writable/session',
        'writable/uploads/'     => $ROOT . '/writable/uploads',
        'writable/logs/'        => $ROOT . '/writable/logs',
        'public/uploads/'       => $ROOT . '/public/uploads',
        '.env writable folder'  => $ROOT,
    ] as $label => $dir) {
        if (!is_dir($dir)) @mkdir($dir, 0775, true);
        $checks[] = [$label . ' writable', is_dir($dir) && is_writable($dir), $dir];
    }
    $checks[] = ['vendor/autoload.php present', is_file($ROOT . '/vendor/autoload.php'), $ROOT . '/vendor/autoload.php'];
    $checks[] = ['app/Database/Migrations present', is_dir($ROOT . '/app/Database/Migrations'), $ROOT . '/app/Database/Migrations'];
    return $checks;
}

function preflight_ok(array $checks): bool { foreach ($checks as $c) if (!$c[1]) return false; return true; }

function gen_encryption_key(): string { return 'hex2bin:' . bin2hex(random_bytes(32)); }

function bootstrap_codeigniter(string $ROOT): \CodeIgniter\CodeIgniter
{
    $_SERVER['HTTP_HOST']     = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $_SERVER['REQUEST_URI']   = '/';
    $_SERVER['SCRIPT_NAME']   = '/index.php';
    $_SERVER['REQUEST_METHOD']= 'GET';

    chdir($ROOT);
    require_once $ROOT . '/app/Config/Paths.php';
    require_once $ROOT . '/system/bootstrap.php';

    $app = \Config\Services::codeigniter();
    $app->initialize();
    return $app;
}

function run_migrations(string $ROOT): array
{
    bootstrap_codeigniter($ROOT);
    $runner = \Config\Services::migrations();
    try {
        $runner->latest();
        return ['ok' => true, 'msg' => 'Migrations applied.'];
    } catch (\Throwable $e) {
        return ['ok' => false, 'msg' => $e->getMessage()];
    }
}

function run_seeders(string $ROOT, array $seeders): array
{
    bootstrap_codeigniter($ROOT);
    $seeder = \Config\Database::seeder();
    $applied = [];
    foreach ($seeders as $name) {
        try { $seeder->call($name); $applied[] = $name; }
        catch (\Throwable $e) { return ['ok' => false, 'msg' => "Seeder $name failed: " . $e->getMessage(), 'applied' => $applied]; }
    }
    return ['ok' => true, 'applied' => $applied];
}

function import_sql_dump(\PDO $pdo, string $sqlFile): array
{
    if (!is_file($sqlFile)) return ['ok' => false, 'msg' => 'database.sql not found in project root.'];

    $sql = file_get_contents($sqlFile);
    if ($sql === false) return ['ok' => false, 'msg' => 'Could not read database.sql'];

    // Split on semicolon at end-of-line. mysqldump output is well-behaved;
    // a more robust split would respect quoted strings, but mysqldump rarely
    // produces those at end-of-line.
    $statements = preg_split('/;\s*\n/', $sql);
    $count = 0;
    $pdo->exec("SET FOREIGN_KEY_CHECKS=0");
    foreach ($statements as $stmt) {
        $stmt = trim($stmt);
        if ($stmt === '' || strpos($stmt, '--') === 0) continue;
        try { $pdo->exec($stmt); $count++; }
        catch (\Throwable $e) {
            $pdo->exec("SET FOREIGN_KEY_CHECKS=1");
            return ['ok' => false, 'msg' => 'Failed: ' . substr($e->getMessage(), 0, 300) . ' on: ' . substr($stmt, 0, 200)];
        }
    }
    $pdo->exec("SET FOREIGN_KEY_CHECKS=1");
    return ['ok' => true, 'count' => $count];
}

function ensure_super_admin(\PDO $pdo, string $email, string $password, string $name): array
{
    // Find or create — admin role first
    $email = strtolower(trim($email));
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) return ['ok' => false, 'msg' => 'Invalid email'];

    $roleId = (int) ($pdo->query("SELECT id FROM roles WHERE role_key = 'admin' LIMIT 1")->fetchColumn() ?: 0);
    if (!$roleId) {
        // Try any role
        $roleId = (int) ($pdo->query("SELECT id FROM roles ORDER BY id ASC LIMIT 1")->fetchColumn() ?: 0);
    }
    if (!$roleId) return ['ok' => false, 'msg' => 'No roles in database — run migrations + permission seeder first.'];

    $stmt = $pdo->prepare("SELECT id FROM users WHERE email = ? LIMIT 1");
    $stmt->execute([$email]);
    $userId = (int) ($stmt->fetchColumn() ?: 0);

    $hash = password_hash($password, PASSWORD_BCRYPT);
    if ($userId) {
        $up = $pdo->prepare("UPDATE users SET password_hash = ?, name = ?, role_id = ?, status = 1, is_super_admin = 1, updated_at = NOW() WHERE id = ?");
        $up->execute([$hash, $name, $roleId, $userId]);
    } else {
        $ins = $pdo->prepare("INSERT INTO users (role_id, name, email, mobile, password_hash, status, is_super_admin, created_at, updated_at) VALUES (?, ?, ?, '', ?, 1, 1, NOW(), NOW())");
        $ins->execute([$roleId, $name, $email, $hash]);
        $userId = (int) $pdo->lastInsertId();
    }
    return ['ok' => true, 'user_id' => $userId];
}

